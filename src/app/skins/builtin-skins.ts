const CLEAR_PIXEL_ICONS = { play: null, pause: null, next: null, previous: null };

/** Built-ins written the way a user writes a skin file, which keeps the parser honest. */
function defineSkin(doc: Record<string, unknown>): Skin {
  const result = parseSkin(doc, new Map([[CLASSIC_SKIN.id, CLASSIC_SKIN]]), CLASSIC_SKIN);
  if (!result.ok) throw new Error(`Built-in skin "${String(doc['name'])}": ${result.error.code}`);
  if (result.invalid.length) throw new Error(`Built-in skin "${String(doc['name'])}": invalid ${result.invalid.join(', ')}`);
  return result.skin;
}

